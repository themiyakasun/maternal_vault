import 'dart:convert';
import 'package:uuid/uuid.dart';

/// The category or origin of the AI/clinical model generating the alert.
enum ModelType {
  maternalRisk,
  pretermRisk,
  mentalHealth,
  clinicalSync,
  general;

  String get displayName {
    switch (this) {
      case ModelType.maternalRisk:
        return 'Maternal Risk XGBoost';
      case ModelType.pretermRisk:
        return 'Preterm Delivery Risk';
      case ModelType.mentalHealth:
        return 'Perinatal Mental Health';
      case ModelType.clinicalSync:
        return 'Clinical Sync Assessment';
      case ModelType.general:
        return 'Clinical Alert System';
    }
  }
}

/// Severity level of the clinical alert.
enum AlertSeverity {
  low,
  moderate,
  high,
  critical;

  String get label {
    switch (this) {
      case AlertSeverity.low:
        return 'Low Risk';
      case AlertSeverity.moderate:
        return 'Moderate Risk';
      case AlertSeverity.high:
        return 'High Risk';
      case AlertSeverity.critical:
        return 'Critical Alert';
    }
  }

  bool get isElevated =>
      this == AlertSeverity.moderate ||
      this == AlertSeverity.high ||
      this == AlertSeverity.critical;

  bool get isUrgent =>
      this == AlertSeverity.high || this == AlertSeverity.critical;
}

/// Represents an alert/notification generated by an AI model or clinical evaluation.
class ModelNotification {
  ModelNotification({
    String? id,
    required this.modelType,
    required this.severity,
    required this.title,
    required this.message,
    this.recommendations = const <String>[],
    DateTime? timestamp,
    this.isRead = false,
    this.metrics = const <String, dynamic>{},
  })  : id = id ?? const Uuid().v4(),
        timestamp = timestamp ?? DateTime.now();

  final String id;
  final ModelType modelType;
  final AlertSeverity severity;
  final String title;
  final String message;
  final List<String> recommendations;
  final DateTime timestamp;
  final bool isRead;
  final Map<String, dynamic> metrics;

  /// Alias for timestamp.
  DateTime get createdAt => timestamp;

  /// Contributing factors extracted from metrics.
  List<String> get contributingFactors {
    final factors = metrics['factors'];
    if (factors is List) {
      return factors.map((e) => e.toString()).toList();
    }
    return const <String>[];
  }

  /// Human-readable model identifier.
  String get modelName {
    switch (modelType) {
      case ModelType.maternalRisk:
        return 'Maternal Health Risk Model (XGBoost)';
      case ModelType.pretermRisk:
        return 'Preterm Birth Risk Predictor';
      case ModelType.mentalHealth:
        return 'Perinatal Mental Health Model';
      case ModelType.clinicalSync:
        return 'Clinical Sync Assessment';
      case ModelType.general:
        return 'Clinical Alert System';
    }
  }

  ModelNotification copyWith({
    String? id,
    ModelType? modelType,
    AlertSeverity? severity,
    String? title,
    String? message,
    List<String>? recommendations,
    DateTime? timestamp,
    bool? isRead,
    Map<String, dynamic>? metrics,
  }) {
    return ModelNotification(
      id: id ?? this.id,
      modelType: modelType ?? this.modelType,
      severity: severity ?? this.severity,
      title: title ?? this.title,
      message: message ?? this.message,
      recommendations: recommendations ?? this.recommendations,
      timestamp: timestamp ?? this.timestamp,
      isRead: isRead ?? this.isRead,
      metrics: metrics ?? this.metrics,
    );
  }

  Map<String, dynamic> toMap() {
    return <String, dynamic>{
      'id': id,
      'model_type': modelType.name,
      'severity': severity.name,
      'title': title,
      'message': message,
      'recommendations_json': jsonEncode(recommendations),
      'created_at': timestamp.toIso8601String(),
      'is_read': isRead ? 1 : 0,
      'metrics_json': jsonEncode(metrics),
    };
  }

  factory ModelNotification.fromMap(Map<String, dynamic> map) {
    List<String> recs = <String>[];
    if (map['recommendations_json'] != null) {
      try {
        final dynamic decoded = jsonDecode(map['recommendations_json'].toString());
        if (decoded is List) {
          recs = decoded.map((dynamic item) => item.toString()).toList();
        }
      } catch (_) {}
    } else if (map['recommendations'] is List) {
      recs = (map['recommendations'] as List)
          .map((dynamic item) => item.toString())
          .toList();
    }

    Map<String, dynamic> met = <String, dynamic>{};
    if (map['metrics_json'] != null) {
      try {
        final dynamic decoded = jsonDecode(map['metrics_json'].toString());
        if (decoded is Map<String, dynamic>) {
          met = decoded;
        }
      } catch (_) {}
    } else if (map['metrics'] is Map<String, dynamic>) {
      met = map['metrics'] as Map<String, dynamic>;
    }

    final typeStr = map['model_type']?.toString() ?? map['modelType']?.toString() ?? 'general';
    final sevStr = map['severity']?.toString() ?? 'low';

    return ModelNotification(
      id: map['id']?.toString(),
      modelType: ModelType.values.firstWhere(
        (e) => e.name == typeStr,
        orElse: () => ModelType.general,
      ),
      severity: AlertSeverity.values.firstWhere(
        (e) => e.name == sevStr,
        orElse: () => AlertSeverity.low,
      ),
      title: map['title']?.toString() ?? 'Clinical Alert',
      message: map['message']?.toString() ?? '',
      recommendations: recs,
      timestamp: map['created_at'] != null
          ? DateTime.tryParse(map['created_at'].toString()) ?? DateTime.now()
          : (map['timestamp'] != null
              ? DateTime.tryParse(map['timestamp'].toString()) ?? DateTime.now()
              : DateTime.now()),
      isRead: map['is_read'] == 1 || map['isRead'] == true,
      metrics: met,
    );
  }

  Map<String, dynamic> toJson() => toMap();

  factory ModelNotification.fromJson(Map<String, dynamic> json) =>
      ModelNotification.fromMap(json);
}
