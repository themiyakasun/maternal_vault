import 'package:flutter/material.dart';
import 'package:intl/intl.dart';

import '../../../../core/constants/app_colors.dart';
import '../../../../core/constants/app_text_styles.dart';
import '../../../../core/theme/app_theme.dart';
import '../../../../data/models/model_notification.dart';
import '../../../../data/services/model_notification_service.dart';
import '../../domain/basic_profile.dart';
import '../../domain/clinic_record.dart';
import '../../domain/key_vitals.dart';
import '../../domain/medical_history.dart';
import '../../domain/obstetric_history.dart';
import '../widgets/model_alert_dialog.dart';
import 'epds_screening_screen.dart';

enum _NotificationFilter { all, unread, elevated }

/// Screen presenting notifications and health recommendations generated by the
/// integrated clinical AI models (Maternal Risk XGBoost, Preterm Risk, and Perinatal Mental Health).
class MotherNotificationsScreen extends StatefulWidget {
  const MotherNotificationsScreen({
    super.key,
    this.profile,
    this.vitals,
    this.history,
    this.obstetric,
    this.clinic,
  });

  final BasicProfile? profile;
  final KeyVitals? vitals;
  final MedicalHistory? history;
  final ObstetricHistory? obstetric;
  final ClinicRecord? clinic;

  static Route<void> route({
    BasicProfile? profile,
    KeyVitals? vitals,
    MedicalHistory? history,
    ObstetricHistory? obstetric,
    ClinicRecord? clinic,
  }) {
    return MaterialPageRoute<void>(
      builder: (BuildContext context) => MotherNotificationsScreen(
        profile: profile,
        vitals: vitals,
        history: history,
        obstetric: obstetric,
        clinic: clinic,
      ),
    );
  }

  @override
  State<MotherNotificationsScreen> createState() =>
      _MotherNotificationsScreenState();
}

class _MotherNotificationsScreenState extends State<MotherNotificationsScreen> {
  _NotificationFilter _selectedFilter = _NotificationFilter.all;
  bool _isEvaluating = false;

  void _openEpdsScreening() {
    Navigator.of(context).push(
      EpdsScreeningScreen.route(
        profile: widget.profile,
        vitals: widget.vitals,
        history: widget.history,
        obstetric: widget.obstetric,
        clinic: widget.clinic,
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final ModelNotificationService service = ModelNotificationService.instance;

    return Scaffold(
      backgroundColor: AppColors.surface,
      appBar: AppBar(
        title: const Text('Clinical AI Alerts'),
        backgroundColor: AppColors.surface,
        surfaceTintColor: Colors.transparent,
        elevation: 0,
        actions: <Widget>[
          IconButton(
            icon: const Icon(Icons.self_improvement_rounded),
            tooltip: 'EPDS & Daily Wellbeing Log',
            onPressed: _openEpdsScreening,
          ),
          ValueListenableBuilder<int>(
            valueListenable: service.unreadCountNotifier,
            builder: (BuildContext context, int unreadCount, _) {
              if (unreadCount == 0) return const SizedBox.shrink();
              return IconButton(
                icon: const Icon(Icons.done_all_rounded),
                tooltip: 'Mark all as read',
                onPressed: () async {
                  await service.markAllAsRead();
                  if (context.mounted) {
                    ScaffoldMessenger.of(context).showSnackBar(
                      const SnackBar(
                        content: Text('All alerts marked as read'),
                        duration: Duration(seconds: 2),
                      ),
                    );
                  }
                },
              );
            },
          ),
          PopupMenuButton<String>(
            icon: const Icon(Icons.more_vert_rounded),
            onSelected: (String value) async {
              if (value == 'clear_all') {
                final bool? confirmed = await showDialog<bool>(
                  context: context,
                  builder: (BuildContext dialogContext) => AlertDialog(
                    title: const Text('Clear All Notifications?'),
                    content: const Text(
                      'This will delete all stored AI model alerts from your device.',
                    ),
                    actions: <Widget>[
                      TextButton(
                        onPressed: () => Navigator.of(dialogContext).pop(false),
                        child: const Text('Cancel'),
                      ),
                      FilledButton(
                        onPressed: () => Navigator.of(dialogContext).pop(true),
                        style: FilledButton.styleFrom(
                          backgroundColor: AppColors.error,
                        ),
                        child: const Text('Clear All'),
                      ),
                    ],
                  ),
                );

                if (confirmed == true) {
                  await service.clearAllNotifications();
                }
              } else if (value == 'evaluate_now') {
                _runEvaluation();
              } else if (value == 'epds_screening') {
                _openEpdsScreening();
              }
            },
            itemBuilder: (BuildContext context) => <PopupMenuEntry<String>>[
              const PopupMenuItem<String>(
                value: 'epds_screening',
                child: Row(
                  children: <Widget>[
                    Icon(Icons.self_improvement_rounded, size: 20),
                    SizedBox(width: 12),
                    Text('10-Item EPDS & Symptom Log'),
                  ],
                ),
              ),
              const PopupMenuItem<String>(
                value: 'evaluate_now',
                child: Row(
                  children: <Widget>[
                    Icon(Icons.auto_awesome_rounded, size: 20),
                    SizedBox(width: 12),
                    Text('Run AI Health Check'),
                  ],
                ),
              ),
              const PopupMenuDivider(),
              const PopupMenuItem<String>(
                value: 'clear_all',
                child: Row(
                  children: <Widget>[
                    Icon(Icons.delete_sweep_rounded, size: 20, color: AppColors.error),
                    SizedBox(width: 12),
                    Text('Clear All Alerts', style: TextStyle(color: AppColors.error)),
                  ],
                ),
              ),
            ],
          ),
        ],
      ),
      floatingActionButton: FloatingActionButton.extended(
        onPressed: _isEvaluating ? null : _runEvaluation,
        icon: _isEvaluating
            ? const SizedBox(
                width: 18,
                height: 18,
                child: CircularProgressIndicator(
                  strokeWidth: 2,
                  color: Colors.white,
                ),
              )
            : const Icon(Icons.auto_awesome_rounded),
        label: Text(_isEvaluating ? 'Evaluating...' : 'Run AI Check'),
        backgroundColor: AppColors.primary,
        foregroundColor: Colors.white,
      ),
      body: ValueListenableBuilder<List<ModelNotification>>(
        valueListenable: service.notificationsNotifier,
        builder: (BuildContext context, List<ModelNotification> allNotifications, _) {
          final List<ModelNotification> filteredNotifications =
              _filterNotifications(allNotifications);

          return Column(
            children: <Widget>[
              _buildFilterChips(allNotifications),
              Expanded(
                child: filteredNotifications.isEmpty
                    ? _buildEmptyState(allNotifications.isEmpty)
                    : ListView.builder(
                        padding: const EdgeInsets.symmetric(
                          horizontal: AppSpacing.screenPadding,
                          vertical: AppSpacing.stackSm,
                        ),
                        itemCount: filteredNotifications.length,
                        itemBuilder: (BuildContext context, int index) {
                          final ModelNotification notification =
                              filteredNotifications[index];
                          return _buildNotificationCard(
                            context,
                            notification,
                            service,
                          );
                        },
                      ),
              ),
            ],
          );
        },
      ),
    );
  }

  Widget _buildFilterChips(List<ModelNotification> allNotifications) {
    final int unreadCount =
        allNotifications.where((ModelNotification n) => !n.isRead).length;
    final int elevatedCount = allNotifications
        .where(
          (ModelNotification n) =>
              n.severity == AlertSeverity.high ||
              n.severity == AlertSeverity.critical,
        )
        .length;

    return SingleChildScrollView(
      scrollDirection: Axis.horizontal,
      padding: const EdgeInsets.symmetric(
        horizontal: AppSpacing.screenPadding,
        vertical: 8,
      ),
      child: Row(
        children: <Widget>[
          ChoiceChip(
            label: Text('All (${allNotifications.length})'),
            selected: _selectedFilter == _NotificationFilter.all,
            onSelected: (bool selected) {
              if (selected) {
                setState(() => _selectedFilter = _NotificationFilter.all);
              }
            },
          ),
          const SizedBox(width: 8),
          ChoiceChip(
            label: Row(
              mainAxisSize: MainAxisSize.min,
              children: <Widget>[
                const Text('Unread'),
                if (unreadCount > 0) ...<Widget>[
                  const SizedBox(width: 6),
                  Container(
                    padding: const EdgeInsets.symmetric(
                      horizontal: 6,
                      vertical: 2,
                    ),
                    decoration: BoxDecoration(
                      color: AppColors.primary,
                      borderRadius: BorderRadius.circular(10),
                    ),
                    child: Text(
                      '$unreadCount',
                      style: const TextStyle(
                        color: Colors.white,
                        fontSize: 11,
                        fontWeight: FontWeight.bold,
                      ),
                    ),
                  ),
                ],
              ],
            ),
            selected: _selectedFilter == _NotificationFilter.unread,
            onSelected: (bool selected) {
              if (selected) {
                setState(() => _selectedFilter = _NotificationFilter.unread);
              }
            },
          ),
          const SizedBox(width: 8),
          ChoiceChip(
            label: Row(
              mainAxisSize: MainAxisSize.min,
              children: <Widget>[
                const Text('Elevated Risk'),
                if (elevatedCount > 0) ...<Widget>[
                  const SizedBox(width: 6),
                  Container(
                    padding: const EdgeInsets.symmetric(
                      horizontal: 6,
                      vertical: 2,
                    ),
                    decoration: BoxDecoration(
                      color: AppColors.error,
                      borderRadius: BorderRadius.circular(10),
                    ),
                    child: Text(
                      '$elevatedCount',
                      style: const TextStyle(
                        color: Colors.white,
                        fontSize: 11,
                        fontWeight: FontWeight.bold,
                      ),
                    ),
                  ),
                ],
              ],
            ),
            selected: _selectedFilter == _NotificationFilter.elevated,
            onSelected: (bool selected) {
              if (selected) {
                setState(() => _selectedFilter = _NotificationFilter.elevated);
              }
            },
          ),
        ],
      ),
    );
  }

  List<ModelNotification> _filterNotifications(
    List<ModelNotification> notifications,
  ) {
    switch (_selectedFilter) {
      case _NotificationFilter.all:
        return notifications;
      case _NotificationFilter.unread:
        return notifications
            .where((ModelNotification n) => !n.isRead)
            .toList();
      case _NotificationFilter.elevated:
        return notifications
            .where(
              (ModelNotification n) =>
                  n.severity == AlertSeverity.high ||
                  n.severity == AlertSeverity.critical,
            )
            .toList();
    }
  }

  Widget _buildEmptyState(bool noAlertsAtAll) {
    return Center(
      child: Padding(
        padding: const EdgeInsets.all(AppSpacing.screenPadding),
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: <Widget>[
            Container(
              padding: const EdgeInsets.all(24),
              decoration: BoxDecoration(
                color: AppColors.secondaryContainer.withValues(alpha: 0.3),
                shape: BoxShape.circle,
              ),
              child: const Icon(
                Icons.check_circle_outline_rounded,
                size: 64,
                color: AppColors.secondary,
              ),
            ),
            const SizedBox(height: 20),
            Text(
              noAlertsAtAll
                  ? 'All Clinical AI Signals Optimal'
                  : 'No Notifications In This Filter',
              style: AppTextStyles.h3,
              textAlign: TextAlign.center,
            ),
            const SizedBox(height: 10),
            Text(
              noAlertsAtAll
                  ? 'Maternal Risk, Preterm Delivery, and Mental Health models have evaluated your clinical records and show healthy progression.'
                  : 'Switch filters or tap "Run AI Check" to perform an on-demand clinical evaluation.',
              style: AppTextStyles.bodySm.copyWith(
                color: AppColors.onSurfaceVariant,
              ),
              textAlign: TextAlign.center,
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildNotificationCard(
    BuildContext context,
    ModelNotification notification,
    ModelNotificationService service,
  ) {
    final Color severityColor = _getSeverityColor(notification.severity);
    final String formattedDate = DateFormat('MMM d, y • h:mm a').format(
      notification.createdAt,
    );

    return Card(
      margin: const EdgeInsets.only(bottom: 12),
      elevation: 0,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(16),
        side: BorderSide(
          color: notification.isRead
              ? AppColors.outlineVariant.withValues(alpha: 0.4)
              : severityColor.withValues(alpha: 0.6),
          width: notification.isRead ? 1.0 : 1.5,
        ),
      ),
      color: notification.isRead
          ? AppColors.surfaceContainerLowest
          : severityColor.withValues(alpha: 0.05),
      child: InkWell(
        borderRadius: BorderRadius.circular(16),
        onTap: () {
          if (!notification.isRead) {
            service.markAsRead(notification.id);
          }
          ModelAlertDialog.show(context, notification);
        },
        child: Padding(
          padding: const EdgeInsets.all(16),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: <Widget>[
              // Header: severity icon, model name, date, unread dot
              Row(
                crossAxisAlignment: CrossAxisAlignment.center,
                children: <Widget>[
                  Container(
                    padding: const EdgeInsets.all(6),
                    decoration: BoxDecoration(
                      color: severityColor.withValues(alpha: 0.15),
                      shape: BoxShape.circle,
                    ),
                    child: Icon(
                      _getSeverityIcon(notification.severity),
                      size: 18,
                      color: severityColor,
                    ),
                  ),
                  const SizedBox(width: 10),
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: <Widget>[
                        Text(
                          notification.modelType.displayName,
                          style: AppTextStyles.labelCaps.copyWith(
                            color: severityColor,
                            fontWeight: FontWeight.bold,
                          ),
                        ),
                        Text(
                          formattedDate,
                          style: AppTextStyles.labelCaps.copyWith(
                            color: AppColors.onSurfaceVariant,
                          ),
                        ),
                      ],
                    ),
                  ),
                  if (!notification.isRead)
                    Container(
                      width: 8,
                      height: 8,
                      decoration: const BoxDecoration(
                        color: AppColors.primary,
                        shape: BoxShape.circle,
                      ),
                    ),
                ],
              ),
              const SizedBox(height: 12),
              // Title
              Text(
                notification.title,
                style: AppTextStyles.h3.copyWith(
                  fontWeight: FontWeight.bold,
                  fontSize: 16,
                ),
              ),
              const SizedBox(height: 6),
              // Message
              Text(
                notification.message,
                style: AppTextStyles.bodySm.copyWith(
                  color: AppColors.onSurface,
                ),
              ),
              // Contributing factors
              if (notification.contributingFactors.isNotEmpty) ...<Widget>[
                const SizedBox(height: 10),
                Wrap(
                  spacing: 6,
                  runSpacing: 4,
                  children: notification.contributingFactors
                      .take(3)
                      .map((String factor) {
                    return Container(
                      padding: const EdgeInsets.symmetric(
                        horizontal: 8,
                        vertical: 3,
                      ),
                      decoration: BoxDecoration(
                        color: AppColors.surfaceContainerHigh,
                        borderRadius: BorderRadius.circular(6),
                      ),
                      child: Text(
                        factor,
                        style: AppTextStyles.labelCaps.copyWith(
                          fontWeight: FontWeight.w500,
                          color: AppColors.onSurfaceVariant,
                        ),
                      ),
                    );
                  }).toList(),
                ),
              ],
              const SizedBox(height: 12),
              // Action Buttons
              Row(
                mainAxisAlignment: MainAxisAlignment.end,
                children: <Widget>[
                  TextButton.icon(
                    onPressed: () {
                      ModelAlertDialog.show(context, notification);
                    },
                    icon: const Icon(Icons.visibility_outlined, size: 16),
                    label: const Text('View Guidance'),
                    style: TextButton.styleFrom(
                      foregroundColor: AppColors.primary,
                      visualDensity: VisualDensity.compact,
                    ),
                  ),
                  const SizedBox(width: 4),
                  IconButton(
                    icon: const Icon(Icons.delete_outline_rounded, size: 20),
                    tooltip: 'Delete notification',
                    color: AppColors.onSurfaceVariant,
                    visualDensity: VisualDensity.compact,
                    onPressed: () async {
                      await service.deleteNotification(notification.id);
                    },
                  ),
                ],
              ),
            ],
          ),
        ),
      ),
    );
  }

  Color _getSeverityColor(AlertSeverity severity) {
    switch (severity) {
      case AlertSeverity.low:
        return AppColors.secondary;
      case AlertSeverity.moderate:
        return const Color(0xFFD97706); // Amber
      case AlertSeverity.high:
        return const Color(0xFFEA580C); // Deep Orange
      case AlertSeverity.critical:
        return AppColors.error;
    }
  }

  IconData _getSeverityIcon(AlertSeverity severity) {
    switch (severity) {
      case AlertSeverity.low:
        return Icons.check_circle_outline_rounded;
      case AlertSeverity.moderate:
        return Icons.info_outline_rounded;
      case AlertSeverity.high:
        return Icons.warning_amber_rounded;
      case AlertSeverity.critical:
        return Icons.emergency_rounded;
    }
  }

  Future<void> _runEvaluation() async {
    setState(() => _isEvaluating = true);
    try {
      final List<ModelNotification> newAlerts =
          await ModelNotificationService.instance.evaluateAndAlert(
        profile: widget.profile ?? const BasicProfile.empty(),
        vitals: widget.vitals ?? const KeyVitals.empty(),
        history: widget.history,
        obstetric: widget.obstetric,
        clinic: widget.clinic,
      );

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(
              newAlerts.isEmpty
                  ? 'Evaluation complete: No new alerts generated.'
                  : 'Evaluation complete: ${newAlerts.length} new alert(s) posted.',
            ),
            duration: const Duration(seconds: 3),
          ),
        );
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Error evaluating models: $e'),
            backgroundColor: AppColors.error,
          ),
        );
      }
    } finally {
      if (mounted) {
        setState(() => _isEvaluating = false);
      }
    }
  }
}
