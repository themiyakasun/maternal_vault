typedef PartnerConnectionData = ({
  PartnerSummary summary,
  PartnerAgenda agenda,
  EmergencyPlan emergencyPlan,
  String motherName,
});

/// Sheet that allows a partner to manually paste or enter the transfer code
/// generated by the mother's app.
class PartnerConnectSheet extends StatefulWidget {
  const PartnerConnectSheet({super.key});

  static Future<PartnerConnectionData?> show(BuildContext context) {
    return showModalBottomSheet<PartnerConnectionData>(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (BuildContext context) => const PartnerConnectSheet(),
    );
  }

  @override
  State<PartnerConnectSheet> createState() => _PartnerConnectSheetState();
}

class _PartnerConnectSheetState extends State<PartnerConnectSheet> {
  final TextEditingController _controller = TextEditingController();
  String? _error;

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  void _pasteFromClipboard() async {
    final data = await Clipboard.getData(Clipboard.kTextPlain);
    if (data != null && data.text != null && data.text!.isNotEmpty) {
      setState(() {
        _controller.text = data.text!.trim();
        _error = null;
      });
    }
  }

  void _submit() {
    final text = _controller.text.trim();
    if (text.isEmpty) {
      setState(() {
        _error = 'Please enter or paste the transfer code.';
      });
      return;
    }

    final parsed = PartnerSyncService.parsePartnerPayload(text);
    if (parsed != null) {
      HapticFeedback.mediumImpact();
      Navigator.of(context).pop(parsed);
    } else {
      HapticFeedback.heavyImpact();
      setState(() {
        _error = 'Invalid transfer code. Please re-copy the code from the mother\'s phone.';
      });
    }
  }

  @override
  Widget build(BuildContext context) {
    final bottomInset = MediaQuery.of(context).viewInsets.bottom;

    return Container(
      decoration: const BoxDecoration(
        color: AppColors.surface,
        borderRadius: BorderRadius.vertical(top: Radius.circular(24)),
      ),
      padding: EdgeInsets.fromLTRB(
        AppSpacing.screenPadding,
        24,
        AppSpacing.screenPadding,
        24 + bottomInset,
      ),
      child: Column(
        mainAxisSize: MainAxisSize.min,
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: <Widget>[
          Row(
            children: <Widget>[
              const Icon(
                Icons.qr_code_scanner_rounded,
                color: AppColors.primary,
                size: 24,
              ),
              const SizedBox(width: 10),
              Text(
                'Enter Transfer Code',
                style: AppTextStyles.h3,
              ),
              const Spacer(),
              IconButton(
                icon: const Icon(Icons.close_rounded),
                onPressed: () => Navigator.of(context).pop(),
              ),
            ],
          ),
          const SizedBox(height: 8),
          Text(
            'Paste the code string generated from the Mother\'s Settings -> "Transfer Data to Partner" screen.',
            style: AppTextStyles.bodySm,
          ),
          const SizedBox(height: 20),
          AppTextField(
            label: 'Transfer Code',
            hint: 'Paste partner sync payload here...',
            controller: _controller,
            maxLines: 4,
          ),
          if (_error != null) ...[
            const SizedBox(height: 6),
            Text(
              _error!,
              style: AppTextStyles.bodySm.copyWith(color: AppColors.error),
            ),
          ],
          const SizedBox(height: 12),
          Align(
            alignment: Alignment.centerRight,
            child: TextButton.icon(
              onPressed: _pasteFromClipboard,
              icon: const Icon(Icons.paste_rounded, size: 18),
              label: const Text('Paste from Clipboard'),
            ),
          ),
          const SizedBox(height: 16),
          AppPrimaryButton(
            label: 'Connect & View Updates',
            onPressed: _submit,
            tone: AppButtonTone.secondary,
            icon: Icons.check_circle_outline_rounded,
          ),
          const SizedBox(height: 12),
          AppOutlineButton(
            label: 'Use Demo Record',
            onPressed: () {
              Navigator.of(context).pop(
                (
                  summary: const PartnerSummary.sample(),
                  agenda: PartnerAgenda.sample(),
                  emergencyPlan: const EmergencyPlan.sample(),
                  motherName: 'Kumari Sandamali Perera',
                ),
              );
            },
            tone: AppButtonTone.secondary,
          ),
        ],
      ),
    );
  }
}
